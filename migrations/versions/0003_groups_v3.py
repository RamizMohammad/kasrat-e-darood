def _migrate_data() -> None:
    from app.core import clock

    op.execute("UPDATE groups SET is_global = true, member_limit = 2000000000 WHERE invite_code = 'GLOBAL00'")

    # Logs in another group's week → the global week they fall in (or, if
    # none covers them, the global active/latest week).
    op.execute("""
        WITH g AS (SELECT id FROM groups WHERE is_global LIMIT 1),
        gw AS (SELECT w.* FROM weekly_sessions w JOIN g ON w.group_id = g.id WHERE w.deleted = false),
        fallback AS (SELECT id FROM gw ORDER BY (status = 'ACTIVE') DESC, week_number DESC LIMIT 1)
        UPDATE submissions s
           SET week_id = COALESCE(
                 (SELECT gw.id FROM gw WHERE s.created_at >= gw.start_date
                    AND s.created_at < COALESCE(gw.locked_at, gw.end_date + interval '1 second')
                  ORDER BY gw.week_number DESC LIMIT 1),
                 (SELECT id FROM fallback))
         WHERE s.week_id IN (SELECT w.id FROM weekly_sessions w
                             WHERE w.group_id NOT IN (SELECT id FROM g))
           AND EXISTS (SELECT 1 FROM g)
    """)
    # Retire the per-group weeks (groups no longer have their own).
    op.execute("""
        UPDATE weekly_sessions SET deleted = true, status = 'ARCHIVED'
         WHERE group_id NOT IN (SELECT id FROM groups WHERE is_global)
           AND EXISTS (SELECT 1 FROM groups WHERE is_global)
    """)
    # Live global week totals = what its logs add up to now.
    op.execute("""
        UPDATE weekly_sessions w SET group_total = COALESCE(
            (SELECT sum(count) FROM submissions s WHERE s.week_id = w.id AND s.deleted = false), 0)
         WHERE w.status = 'ACTIVE' AND w.deleted = false
    """)
    # The open week closes at the next Friday close (around Maghrib).
    op.execute(sa.text("UPDATE weekly_sessions SET end_date = :end WHERE status = 'ACTIVE' AND deleted = false")
               .bindparams(end=clock.next_week_close()))


